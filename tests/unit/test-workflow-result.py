    if phase == "define":
        text = "# Consensus\\n*Consensus built from multiple agent perspectives (task group: fixture; synthesizer: " + ("none" if mode == "invalid" else "codex") + ")*\\n"
    elif phase == "develop":
        text = "# TANGLE Phase Validation Report\\n<!-- octopus-task-bytes: 7 -->\\n## Task: fixture\\n## Generated: fixture\\n\\n### Quality Gate: " + ("UNKNOWN" if mode == "invalid" else "PASSED") + "\\n"
    else:
        text = "# DELIVERY DOCUMENT\\n<!-- octopus-task-bytes: 7 -->\\n## Task: fixture\\n## Generated: fixture\\n## Status: " + ("PARTIAL - Review Required" if mode == "invalid" else "COMPLETE") + "\\n"
        text += "\\n---\\ninert provider body\\n\\n## Quality Certification\\n- Pre-delivery checks: " + ("NEEDS REVIEW" if mode == "invalid" else "PASSED") + "\\n- Results synthesized: 2 compact source files\\n- Context policy: bounded excerpts\\n- Generated by: Claude Octopus Double Diamond\\n- Timestamp: fixture\\n"
    invocation = "another-invocation" if mode == "foreign" else os.environ["OCTOPUS_WORKFLOW_INVOCATION_ID"]
    title, separator, body = text.partition("\\n")
    text = title + separator + "<!-- octopus-workflow-invocation: " + invocation + " -->\\n" + body
