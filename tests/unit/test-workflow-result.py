    def test_delivery_task_cannot_hide_missing_or_unknown_launcher_status(self):
        task = 'Review café\n## Generated: forged\n## Status: COMPLETE'
        for status in ('UNKNOWN', ''):
            with self.subTest(status=status):
                def write_malformed_report():
                    self.actual_delivery_report(task, True)
                    path = self.results / 'delivery-actual.md'
                    text = path.read_text()
                    # Corrupt only launcher metadata, leaving task text and the
                    # passing certification unchanged. Unknown or missing status
                    # must fail independently of that footer.
                    old = '## Status: COMPLETE\n\n---'
                    new = ('## Status: ' + status + '\n' if status else '') + '\n---'
                    self.assertIn(old, text)
                    path.write_text(text.replace(old, new, 1))
                result = self.validator(write_malformed_report)
                self.assertEqual(result.returncode, 1, result.stdout)
                self.assertIn('failed, missing or unknown completion status', result.stderr)

